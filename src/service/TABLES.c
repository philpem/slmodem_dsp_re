/*
 * TABLES.c -- the MTK trigonometric and bit-count tables.
 *
 * Reconstructed from dsplibs.o, .data:
 *
 *   MTK_xor_table   .data 0x008500    512 bytes   256 x short
 *   MTK_atan_table  .data 0x008700  1,028 bytes   257 x float
 *   MTK_sin_table   .data 0x008b20  1,028 bytes   257 x float
 *   MTK_cos_table   .data 0x008f40  1,028 bytes   257 x float
 *   MTK_sin_sign    .data 0x009344     16 bytes     4 x float
 *   MTK_cos_sign    .data 0x009354     16 bytes     4 x float
 *
 * THE TRANSLATION UNIT IS RECOVERED (finding F11400).  The blob's FILE
 * order is `silence.c` (272), `PHASOR.c` (273), `TABLES.c` (274), `pcm.c`
 * (275), and `.data` is concatenated in that order: `silence_level_table`
 * is the last silence.c symbol at 0x84d4, `_a2u`/`_u2a` the first pcm.c
 * symbols at 0x9380/0x9400, and the six tables above fill the window
 * between them with no other translation unit's object in it.  So the
 * block is PHASOR.c's or TABLES.c's, and since PHASOR.c is `MTK_phasor`
 * (its own FILE, recovered by the `.text` bracket) the whole block is
 * `TABLES.c`'s -- the assignment that does NOT split one contiguous data
 * block on address alone (F11393).
 *
 * (`.data` offsets, so `bannercheck.py` -- which reads `.text` banners --
 * does not and should not see them.)
 *
 * WHAT THE SHAPE IS, read out of `MTK_phasor` (0xb0690) which is the only
 * caller of the sine pair:
 *
 *   - the angle is reduced to [0, 1) turns, scaled by 1024 and rounded to a
 *     16-bit integer; the low 8 bits index the table and bits 8-9 select the
 *     quadrant, so an index runs 0..255 and the interpolation reads
 *     `[i]` and `[i+1]` -- which is why the tables are 257 long and not 256;
 *   - `MTK_cos_sign[q]` and `MTK_sin_sign[q]` are then multiplied in, so the
 *     stored quarter wave carries no sign of its own.
 *
 * THE CLOSED FORMS, MEASURED RATHER THAN ASSUMED (finding F8772).  All three
 * float tables are within one ULP of an obvious generator and NONE of them
 * reproduces it bit for bit, so they stay literal, which is what
 * `docs/coefficients.md` and the fast pass both say to do:
 *
 *   MTK_sin_table[i] = sin(i * pi / 512)      1 of 257 entries differs
 *   MTK_cos_table[i] = cos(i * pi / 512)      2 of 257 entries differ
 *   MTK_atan_table[i] = atan(i / 256.0)       1 of 257 entries differs
 *
 * and two exact identities that ARE bit for bit, so they are checked rather
 * than described: `MTK_cos_table[i] == MTK_sin_table[256 - i]` for all 257,
 * and `MTK_xor_table[i] == popcount(i)` for all 256 -- the second is the
 * whole derivation of that table, and the name is the author's word for a
 * parity/Hamming-weight lookup.
 *
 * These are DATA ONLY, and `MTK_phasor` -- which was unwritten when this file
 * landed and is the reason the sentence here used to say so -- is now
 * reconstructed in `src/service/PHASOR.c`.  So the sine pair and both sign
 * vectors have a reader in `src/` again; `MTK_atan_table` and
 * `MTK_xor_table` still do not, and are emitted because they are global.
 * `t_mtktab` proves every byte of all six against the blob's own copies
 * whatever reads them, which is why this file did not have to wait for that
 * function and does not now depend on it.
 */

