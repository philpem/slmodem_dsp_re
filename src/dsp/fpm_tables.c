/*
 * fpm_tables.c -- the Fixed Point Modem library's eight .rodata tables.
 *
 * Reconstructed from dsplibs.o fpm_tables.c (FILE 255).  The object defines
 * all eight as GLOBAL objects in .rodata, 0x00c4a0..0x00cfe2, filling the
 * window between fpm_log10.c's FPM_log10_table and fpm_tone.c's FPM_TONE_CFG
 * with no other translation unit's object in it (F11402).  The namesake
 * assignment is impossible: FPM_SRE_CFG (0xc4e0) precedes FPM_sqrt_table
 * (0xc520) although fpm_sqrt.c is the earlier FILE record, and .rodata is
 * concatenated in FILE order (F11402).
 *
 * THREE OF THESE WERE RECONSTRUCTED AS FILE-`r` STATICS behind accessor
 * functions -- FPM_sqrt_table, FPM_sin_table and FPM_cos_table.  The object
 * defines them GLOBAL (`readelf -sW`: OBJECT GLOBAL .rodata), so hiding them
 * was wrong; they are the object's globals here, and the accessors that used
 * to be their only readers now read the globals.
 *
 * GCC 3.4.2 emits .rodata globals in REVERSE declaration order, so the
 * definitions below are the REVERSE of the object's ascending address order
 * (F11402).  The five tables kept verbatim from their old files are
 * FPM_PPS_CFG, FPM_SRE_CFG, FPM_div_table, FPM_xor_table and FPM_atan_table.
 */

