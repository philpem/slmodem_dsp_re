void
V34EchoCleanUp(struct v34_echo *e)
{
	unsigned i;

	e->cursor = e->dline;

	/*
	 * The coefficients, both halves, and the tap history.
	 *
	 * NOT the delay line.  `dline` keeps whatever it held, which under the
	 * harness's fill is the fill pattern and on a real modem is the tail
	 * of the previous connection.  It is not obviously harmless -- the
	 * next V34EchoFilter convolves fresh coefficients against stale
	 * samples -- but the coefficients are zero at that point, so the
	 * first output is zero regardless and the line has been overwritten
	 * by the time they are not.  Registered as D26 and reproduced.
	 */
	for (i = 0; i < e->taps; i++) {
		e->coeff[i] = 0;
		e->coeff_frac[i] = 0;
		e->hist[i] = 0;
	}

	/*
	 * THE STRING IS THE OBJECT'S, and it is not this function's name.
	 * .rodata.str1.4+0xf848 is "V34FLO: Echo running in Original
	 * Integer...", referenced from here and nowhere else -- so the author
	 * used the clean-up to announce which of two echo-canceller builds is
	 * live, floating point or integer.  An invented "V34EchoCleanUp\n"
	 * stood here until the handshake's transcript comparison ran over
	 * this call tree for the first time; finding 172 is the same defect
	 * in `V34SetupModulator`, and finding 134 is why it survived.
	 */
	if (DSPLIB_DEBUG_ON())
		dsplibs_debug_printf(
			"V34FLO: Echo running in Original Integer...\r\n");
}

void
V34EchoUpdateDelayLine(struct v34_echo *e, short sample)
{
	short *p = e->cursor;

	*p = sample;
	p++;
	if (p >= e->dline + e->dlen)
		p = e->dline;
	e->cursor = p;
}

int
V34EchoFilter(struct v34_echo *e, short lag)
{
	unsigned taps = e->taps;
	short *hist = e->hist;
	const short *p;
	int acc = 0;
	unsigned k;

	/*
	 * Shift the history down by one, discarding the oldest.  Skipped
	 * entirely when there is only one tap, which is the original's own
	 * special case rather than an optimisation added here.
	 */
	if (taps != 1)
		for (k = 0; k < taps - 1; k++)
			hist[k] = hist[k + 1];

	/*
	 * The newest entry comes from `lag + taps` shorts past the cursor,
	 * wrapped once.
	 *
	 * ONCE is the word.  The original subtracts the delay line's length a
	 * single time, so an index more than one length past the end stays
	 * past the end and the read leaves the buffer.  Whether that is
	 * reachable depends on the range of `lag` at the two call sites in
	 * V34RX.c, which is not yet reconstructed; see docs/deviations.md,
	 * D27.  Reproduced, because a second wrap would be a different
	 * function and no differential test could say which the caller wants.
	 */
	p = e->cursor + lag + taps - 1;
	if (p >= e->dline + e->dlen)
		p -= e->dlen;
	hist[taps - 1] = *p;

	for (k = 0; k < taps; k++)
		acc += e->coeff[k] * hist[k];

	return acc;
}

void
V34EchoAdapt(struct v34_echo *e, short err)
{
	unsigned k;

	/*
	 * The 32-bit tap is reassembled from its two halves, moved, and split
	 * again.  `coeff_frac` is read as UNSIGNED and `coeff` as signed,
	 * which is what makes the pair a single two's-complement 32-bit value
	 * rather than two independent numbers.
	 */
	for (k = 0; k < e->taps; k++) {
		int tap = (int)((unsigned)e->coeff[k] << 16)
			  + (unsigned short)e->coeff_frac[k];

		tap = (int)((unsigned)tap + (unsigned)(e->hist[k] * err));

		e->coeff[k] = (short)(tap >> 16);
		e->coeff_frac[k] = (short)tap;
	}
}

int
V34EchoEstimateDelayLineEnergy(struct v34_echo *e)
{
	int acc = 0;
	unsigned k;

	/*
	 * Named for the delay line and computed over the tap HISTORY, which
	 * is a different array.  The name is the original's; the arithmetic is
	 * `e->hist`, unambiguously, at +0x10.
	 */
	for (k = 0; k < e->taps; k++)
		acc = (int)((unsigned)acc
			    + (unsigned)((e->hist[k] * e->hist[k]) >> 5));

	return acc;
}

void
V34EchoHistoryBackwardClean(void *objp, unsigned n)
{
	struct v34_object *obj = (struct v34_object *)objp;
	struct v34_echo_prefilter *pf = &obj->prefilter;
	unsigned span;
	int i;

	/*
	 * The pre-filter's history first.  If the rollback covers the whole
	 * buffer it is cleared outright; otherwise `n` entries are cleared
	 * circularly from the current position.
	 */
	if (n >= (unsigned)pf->hist_len) {
		sysdep_memset(pf->state, 0,
			      (unsigned)pf->hist_len * sizeof(short));
	} else if ((int)n > 0) {
		short *p = &pf->state[pf->hist_pos];
		short *end = &pf->state[pf->hist_len];
		unsigned k = n;

		for (;;) {
			*p++ = 0;
			if (p == end)
				p = pf->state;
			if (--k == 0)
				break;
		}
	}

	/*
	 * Then both cancellers, but only by the part of the rollback that
	 * exceeds HALF of `span` -- the first half is absorbed by the
	 * pre-filter's own delay and does not reach the line.
	 */
	span = (unsigned)pf->span >> 1;
	if (n > span) {
		echo_rewind(&obj->echo0, (int)(n - span));
		echo_rewind(&obj->echo1, (int)(n - span));
	}

	sysdep_memset(obj->scratch_210c, 0, sizeof(obj->scratch_210c));
	sysdep_memset(obj->scratch_20e0, 0, sizeof(obj->scratch_20e0));

	/*
	 * And the last three samples queued for transmission, rolled back
	 * along with the canceller's history -- which is what makes this
	 * function's name literal.  Walked backwards from the transmit
	 * queue's write cursor, clearing only the low short of each; the
	 * wrap is spelled as a second cursor running down from a base four
	 * bytes below the object.  See findings 109.
	 */
	{
		int *p = obj->txq.wr - 1;
		char *base = (char *)obj - 4;

		for (i = 2; i >= 0; i--) {
			short *q;

			if (p >= obj->txq.ring) {
				q = (short *)p;
			} else {
				q = (short *)(base + 0x25c0);
				base -= 4;
			}
			*q = 0;
			p--;
		}
	}
}

